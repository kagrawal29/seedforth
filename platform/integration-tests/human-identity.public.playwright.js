async (page) => {
  const base = 'https://185.192.96.100';
  const callback = 'http://127.0.0.1:18791/callback';
  const password = 'public-qualification-passphrase-2026';
  const check = (v, m) => { if (!v) throw new Error(m); };
  const invitation = await (await page.request.get('http://127.0.0.1:18791/seedforth-public-invitation.json')).json();
  await page.goto(base + '/enroll');
  await page.getByLabel('Invitation',{exact:true}).fill(invitation.invitation);
  await page.getByLabel('Username',{exact:true}).fill('public-qualification-cajon');
  await page.getByLabel('Passphrase (14–256 characters)',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Set up authenticator',exact:true}).click();
  await page.getByRole('heading',{name:'Set up your authenticator'}).waitFor();
  const secret = await page.locator('#totp-secret').innerText();
  const otp = now => page.evaluate(async ({secret,now}) => {
    const alphabet='ABCDEFGHIJKLMNOPQRSTUVWXYZ234567'; let bits='';
    for (const c of secret) bits += alphabet.indexOf(c).toString(2).padStart(5,'0');
    const key=new Uint8Array(Math.floor(bits.length/8));
    for (let i=0;i<key.length;i++) key[i]=parseInt(bits.slice(i*8,i*8+8),2);
    const counter=new Uint8Array(8); new DataView(counter.buffer).setBigUint64(0,BigInt(Math.floor(now/30)));
    const imported=await crypto.subtle.importKey('raw',key,{name:'HMAC',hash:'SHA-1'},false,['sign']);
    const signed=new Uint8Array(await crypto.subtle.sign('HMAC',imported,counter));
    const offset=signed[signed.length-1]&15;
    return ((new DataView(signed.buffer).getUint32(offset)&0x7fffffff)%1000000).toString().padStart(6,'0');
  },{secret,now});
  await page.getByLabel('Authenticator code',{exact:true}).fill(await otp(Date.now()/1000));
  await page.getByRole('button',{name:'Confirm authenticator'}).click();
  await page.getByRole('heading',{name:'Save your recovery codes'}).waitFor();
  check((await page.locator('.recovery-code').count())===8,'Public enrollment did not issue recovery codes');
  await page.getByRole('link',{name:'I saved my recovery codes'}).click();
  await page.getByRole('heading',{name:'Your access'}).waitFor();
  check(await page.evaluate(()=>localStorage.length===0&&sessionStorage.length===0),'Credential entered browser storage');
  check(await page.evaluate(()=>document.cookie===''),'Credential readable by script');
  const registration=await page.request.post(base+'/register',{data:{client_name:'Public qualification client',token_endpoint_auth_method:'none',redirect_uris:[callback],grant_types:['authorization_code'],response_types:['code'],scope:'mycelium'}});
  check(registration.status()===201,'Public OAuth registration failed');
  const client=await registration.json();
  const verifier='public-qualification-verifier-abcdefghijklmnopqrstuvwxyz123456789';
  const challenge=await page.evaluate(async value=>{const b=new Uint8Array(await crypto.subtle.digest('SHA-256',new TextEncoder().encode(value)));return btoa(String.fromCharCode(...b)).replaceAll('+','-').replaceAll('/','_').replace(/=+$/,'');},verifier);
  const query=Object.entries({client_id:client.client_id,redirect_uri:callback,resource:base+'/mcp',response_type:'code',scope:'mycelium',state:'public-state',code_challenge:challenge,code_challenge_method:'S256'}).map(([k,v])=>encodeURIComponent(k)+'='+encodeURIComponent(v)).join('&');
  await page.goto(base+'/authorize?'+query);
  await page.getByRole('heading',{name:'Connect a client'}).waitFor();
  await page.locator('input[type=checkbox]').check();
  await page.getByRole('button',{name:'Allow selected projects'}).click();
  await page.waitForURL(callback+'?**');
  const params=await page.evaluate(()=>Object.fromEntries(new URL(location.href).searchParams));
  check(params.state==='public-state'&&params.code,'Public OAuth callback missing code');
  const issued=await page.request.post(base+'/token',{form:{client_id:client.client_id,grant_type:'authorization_code',code:params.code,code_verifier:verifier,redirect_uri:callback,resource:base+'/mcp'}});
  check(issued.status()===200,'Public OAuth token exchange failed');
  const token=await issued.json();
  const read=await page.request.post(base+'/mcp',{headers:{Authorization:'Bearer '+token.access_token,Accept:'application/json, text/event-stream','MCP-Protocol-Version':'2025-11-25'},data:{jsonrpc:'2.0',id:1,method:'tools/call',params:{name:'read_work',arguments:{scope:'cajon-sensei'}}}});
  check(read.status()===200,'Public token did not reach MCP');
  const result=await read.json(); check(result.result?.structuredContent?.data,'Public MCP read returned no scoped data');
  const denied=await page.request.post(base+'/mcp',{headers:{Authorization:'Bearer '+token.access_token,Accept:'application/json, text/event-stream','MCP-Protocol-Version':'2025-11-25'},data:{jsonrpc:'2.0',id:2,method:'tools/call',params:{name:'read_work',arguments:{scope:'flowing-indian'}}}});
  check((await denied.json()).result?.structuredContent?.error==='scope_denied','Public MCP scope isolation failed');
  return {status:'passed',checks:['external HTTPS enrollment and MFA','no browser credential storage','external OAuth registration, PKCE, consent, callback and token exchange','public scoped MCP read and foreign-scope denial']};
}
